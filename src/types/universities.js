// 🔹 Helpers
export const getUniversityById = (id) => {
    return kenyanUniversities.find(uni => uni.id === id);
};
export const getUniversityNames = () => {
    return kenyanUniversities.map(uni => uni.name);
};
export const getUniversitiesWithBranches = () => {
    return kenyanUniversities.filter(uni => uni.branches && uni.branches.length > 0);
};
export const universityHasBranches = (universityName) => {
    const university = kenyanUniversities.find(uni => uni.name === universityName);
    return !!(university?.branches && university.branches.length > 0);
};
export const getUniversityBranches = (universityName) => {
    const university = kenyanUniversities.find(uni => uni.name === universityName);
    return university?.branches || [];
};
